export const formatArrivalDate = (dateStr, lang) => {
    if (!dateStr || String(dateStr).trim() === '' || String(dateStr).toLowerCase() === 'nan') {
        if (lang === 'KR') return '도착예정일 미정';
        if (lang === 'TH') return 'ยังไม่กำหนดวันที่สินค้าเข้า';
        if (lang === 'JP') return '入荷日未定';
        return 'Arrival Date TBD';
    }
    
    const cleanDate = String(dateStr).trim().toUpperCase();
    if (cleanDate === 'TBD') {
        if (lang === 'KR') return '도착예정일 미정';
        if (lang === 'TH') return 'ยังไม่กำหนดวันที่สินค้าเข้า';
        if (lang === 'JP') return '入荷日未定';
        return 'Arrival Date TBD';
    }
    
    // Check if matches M/D or M/D/YYYY or similar (e.g. 5/8)
    if (cleanDate.includes('/')) {
        const parts = cleanDate.split('/');
        if (parts.length >= 2) {
            const m = Number(parts[0]);
            const d = Number(parts[1]);
            if (!isNaN(m) && !isNaN(d)) {
                if (lang === 'KR') return `${m}월 ${d}일 도착예정`;
                if (lang === 'JP') return `${m}月 ${d}日 入荷予定`;
                if (lang === 'TH') return `คาดว่าจะถึงวันที่ ${d}/${m}`;
                return `Expected to arrive on ${m}/${d}`;
            }
        }
    }
    
    // Fallback if they write something else
    return dateStr;
};

export const getTranslation = (lang, key) => {
    if (!key) return key;
    const l = translations[lang] || translations['KR'];
    
    // 1. Exact match
    if (l[key]) return l[key];
    
    // 2. Trimmed match
    const trimmedKey = String(key).trim();
    if (l[trimmedKey]) return l[trimmedKey];

    // 3. Space-removed match (for cases like "A / B" vs "A/B")
    const noSpaceKey = trimmedKey.replace(/\s+/g, '');
    for (const [k, v] of Object.entries(l)) {
        if (k.replace(/\s+/g, '') === noSpaceKey) {
            return v;
        }
    }
    
    return key;
};

export default translations;

